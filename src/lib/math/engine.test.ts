const show = (ps: PointQ[]) => ps.map(pointToString).sort();

describe('Rational', () => {
  it('normalises sign and lowest terms', () => {
    expect(new Rational(6n, -4n).toString()).toBe('-3/2');
    expect(Rational.parse(' 129 / 100 ').toString()).toBe('129/100');
    expect(new Rational(0n, 5n).d).toBe(1n);
  });
  it('does exact arithmetic', () => {
    const a = Rational.of(1, 3);
    expect(a.add(Rational.of(1, 6)).toString()).toBe('1/2');
    expect(a.sub('1/3').isZero()).toBe(true);
    expect(a.mul(3).eq(1)).toBe(true);
    expect(a.div('2/9').toString()).toBe('3/2');
    expect(() => a.div(0)).toThrow();
    expect(() => Rational.parse('1/0')).toThrow();
    expect(() => Rational.parse('abc')).toThrow();
  });
  it('toNumber survives huge values', () => {
    const big = new Rational(10n ** 400n + 1n, 10n ** 399n);
    expect(big.toNumber()).toBeCloseTo(10, 10);
  });
  it('isqrt is exact for big inputs', () => {
    const n = 12345678901234567890123456789n;
    expect(isqrt(n * n)).toBe(n);
    expect(isSquare(n * n + 1n)).toBe(false);
  });
});

describe('group law over Q', () => {
  it('(1,2) + (3,4) = (−3,2) on y² = x³ − 7x + 10', () => {
    const E = CurveQ.short(-7, 10);
    expect(pointEq(E.add(pt(1, 2), pt(3, 4)), pt(-3, 2))).toBe(true);
  });
  it('2(3,5) = (129/100, −383/1000) on y² = x³ − 2', () => {
    const E = CurveQ.short(0, -2);
    expect(pointToString(E.double(pt(3, 5)))).toBe('(129/100, -383/1000)');
    expect(pointEq(E.add(pt(3, 5), pt(3, 5)), E.mul(2, pt(3, 5)))).toBe(true);
  });
  it('identity, inverses and vertical lines give O', () => {
    const E = CurveQ.short(-7, 10);
    const P = pt(1, 2);
    expect(pointEq(E.add(P, null), P)).toBe(true);
    expect(pointEq(E.add(null, P), P)).toBe(true);
    expect(E.add(P, E.neg(P))).toBeNull();
    expect(E.add(null, null)).toBeNull();
  });
  it('doubling a 2-torsion point gives O', () => {
    const E = CurveQ.short(-1, 0);
    expect(E.double(pt(0, 0))).toBeNull();
    expect(E.order(pt(1, 0))).toBe(2);
  });
  it('is associative and commutative on sample points', () => {
    const E = CurveQ.short(-7, 10);
    const [P, Q, R] = [pt(1, 2), pt(3, 4), pt(-3, -2)];
    expect(pointEq(E.add(E.add(P, Q), R), E.add(P, E.add(Q, R)))).toBe(true);
    expect(pointEq(E.add(P, Q), E.add(Q, P))).toBe(true);
    expect(pointEq(E.mul(5, P), E.add(E.mul(2, P), E.mul(3, P)))).toBe(true);
    expect(pointEq(E.mul(-3, P), E.neg(E.mul(3, P)))).toBe(true);
  });
  it('third(P,Q) is collinear with P and Q', () => {
    const E = CurveQ.short(-7, 10);
    const T = E.third(pt(1, 2), pt(3, 4))!;
    expect(pointToString(T)).toBe('(-3, -2)');
    expect(E.has(T)).toBe(true);
  });
  it('rejects singular curves and off-curve points', () => {
    expect(() => CurveQ.short(0, 0).add(pt(1, 1), pt(1, 1))).toThrow(SingularCurveError);
    expect(() => CurveQ.short(-3, 2).double(pt(1, 0))).toThrow(SingularCurveError);
    expect(() => CurveQ.short(-7, 10).add(pt(1, 3), null)).toThrow(RangeError);
    expect(new CurveQ(0, 0, 0).isSingular()).toBe(true);
  });
  it('heights grow under doubling on y² = x³ − 2', () => {
    const E = CurveQ.short(0, -2);
    const P = pt(3, 5);
    const hs = [1, 2, 4, 8].map((n) => height(E.mul(n, P)));
    expect(hs[0]).toBeCloseTo(Math.log(3), 12);
    expect(hs[1]).toBeCloseTo(Math.log(129), 12);
    expect(hs[2]).toBeGreaterThan(3 * hs[1]);
    expect(hs[3]).toBeGreaterThan(3 * hs[2]);
    expect(E.order(P)).toBeNull();
  });
});

describe('torsion (Nagell–Lutz)', () => {
  it('y² = x³ − x has Z/2 × Z/2', () => {
    const E = CurveQ.short(-1, 0);
    const r = nagellLutz(E);
    expect(show(r.torsion.map((t) => t.P))).toEqual(['(-1, 0)', '(0, 0)', '(1, 0)']);
    expect(r.torsion.every((t) => t.order === 2)).toBe(true);
    expect(torsionOrder(E)).toBe(4);
  });
  it('y² = x³ − 43x + 166 has Z/7 generated by (3,8)', () => {
    const E = CurveQ.short(-43, 166);
    expect(E.disc().toString()).toBe('-425984');
    expect(425984).toBe(2 ** 15 * 13);
    expect(E.order(pt(3, 8))).toBe(7);
    const multiples = [1, 2, 3, 4, 5, 6].map((k) => E.mul(k, pt(3, 8)));
    expect(show(multiples)).toEqual(show([pt(3, 8), pt(3, -8), pt(-5, 16), pt(-5, -16), pt(11, 32), pt(11, -32)]));
    expect(torsionOrder(E)).toBe(7);
  });
  it('y² = x³ + 1 has Z/6', () => {
    const E = CurveQ.short(0, 1);
    const r = nagellLutz(E);
    expect(show(r.torsion.map((t) => t.P))).toEqual(show([pt(-1, 0), pt(0, 1), pt(0, -1), pt(2, 3), pt(2, -3)]));
    expect(E.order(pt(2, 3))).toBe(6);
    expect(torsionOrder(E)).toBe(6);
  });
  it('Nagell–Lutz candidates are necessary, not sufficient', () => {
    // (3,5) on y² = x³ − 2 has integer coordinates but 25 ∤ D = −108, so it is not even a candidate
    const r = nagellLutz(CurveQ.short(0, -2));
    expect(r.torsion).toEqual([]);
    // y² = x³ + 17 has integer points with y² | D? none of them is torsion
    expect(torsionOrder(CurveQ.short(0, 17))).toBe(1);
  });
  it('integer roots helper', () => {
    expect(integerRootsCubic(0n, -1n, 0n)).toEqual([-1n, 0n, 1n]);
    expect(integerRootsCubic(0n, 0n, 0n)).toEqual([0n]);
    expect(integerRootsCubic(0n, 0n, -8n)).toEqual([2n]);
  });
});

describe('integer points', () => {
  it('y² = x³ + 17 has exactly these 16 integer points with −3 ≤ x ≤ 6000', () => {
    const pts = CurveQ.short(0, 17).integerPoints(-3n, 6000n);
    const xs = [...new Set(pts.map((P) => P.x.toString()))];
    expect(xs).toEqual(['-2', '-1', '2', '4', '8', '43', '52', '5234']);
    expect(pts.length).toBe(16);
    expect(5234n ** 3n + 17n).toBe(378661n ** 2n);
  });
  it('congruent-number points', () => {
    expect(CurveQ.short(-25, 0).has(pt(-4, 6))).toBe(true);
    expect(CurveQ.short(-36, 0).has(pt(-3, 9))).toBe(true);
  });
});

describe('2-descent', () => {
  it('squarefree part', () => {
    expect(squarefreePart(-12n)).toBe(-3n);
    expect(squarefreePart(4n)).toBe(1n);
    expect(squarefreePart(-1n)).toBe(-1n);
  });
  it('y² = x³ − x has rank 0', () => {
    const r = twoDescent(0, -1);
    expect(r.E.found).toEqual([-1n, 1n]);
    expect(r.Ebar.found).toEqual([1n, 2n]);
    expect(r.Ebar.undecided).toEqual([]);
    expect(r.rank).toBe(0);
  });
  it('y² = x³ − 25x (5 is congruent) has rank 1', () => {
    expect(twoDescent(0, -25).rank).toBe(1);
  });
  it('y² = x³ + x has rank 0 and y² = x³ − 5x has rank 1', () => {
    expect(twoDescent(0, 1).rank).toBe(0);
    expect(twoDescent(0, -5).rank).toBe(1);
  });
  it('bounds always bracket the answer', () => {
    const r = twoDescent(0, -17);
    expect(r.rankLower).toBeLessThanOrEqual(r.rankUpper);
    expect(r.rankLower).toBeGreaterThanOrEqual(0);
  });
});

describe('finite fields', () => {
  it('Hasse bound holds for all odd primes p < 1000 of good reduction', () => {
    const curves: [number, number, number][] = [[0, -1, 0], [0, -43, 166], [0, 0, 17], [0, -7, 10], [1, 1, 1]];
    let checked = 0;
    for (const [a2, a4, a6] of curves) for (const p of primesBelow(1000)) {
      if (p === 2) continue;
      const E = new CurveFp(a2, a4, a6, p);
      if (E.isSingular()) continue;
      expect(withinHasse(E.count(), p), `p=${p} curve=${a2},${a4},${a6}`).toBe(true);
      checked++;
    }
    expect(checked).toBeGreaterThan(800);
  });
  it('count() agrees with listing points, and the group law stays on the curve', () => {
    for (const p of [5, 7, 11, 13, 101]) {
      const E = new CurveFp(0, -7, 10, p);
      if (E.isSingular()) continue;
      const pts = E.points();
      expect(pts.length + 1).toBe(E.count());
      for (const P of pts.slice(0, 6)) for (const Q of pts.slice(0, 6)) expect(E.has(E.add(P, Q))).toBe(true);
      // Lagrange: N·P = O
      for (const P of pts.slice(0, 6)) expect(E.mul(E.count(), P)).toBeNull();
    }
  });
  it('x³ + y³ = 1 over F₇ has 6 affine points; 4·7 = 1² + 27·1²', () => {
    expect(countFermatCubicAffine(7)).toBe(6);
    expect(4 * 7).toBe(1 + 27);
    // p ≡ 2 mod 3: cubing is a bijection, so exactly p affine points
    for (const p of [5, 11, 17, 23]) expect(countFermatCubicAffine(p)).toBe(p);
  });
  it('modular helpers', () => {
    expect(modInverse(3n, 7n)).toBe(5n);
    expect(modInverse(6n, 9n)).toBeNull();
    expect(modPow(2n, 10n, 1000n)).toBe(24n);
  });
});

describe('factoring', () => {
  it('ECM finds 26927 | 1715761513', () => {
    const n = 1715761513n;
    expect(26927n * 63719n).toBe(n);
    const r = ecm(n);
    expect(r).not.toBeNull();
    expect([26927n, 63719n]).toContain(r!.factor);
    expect(n % r!.factor).toBe(0n);
    expect(r!.failedAt).toBeGreaterThan(0);
  });
  it('Pollard p−1 factors a number with a smooth p−1', () => {
    // 421 − 1 = 2²·3·5·7 is smooth; 1000003 − 1 = 2·3·166667 is not
    const f = pollardPm1(421n * 1000003n, 50);
    expect(f).toBe(421n);
  });
});

describe('modularity of 11a', () => {
  it('a_p(11a) equals the coefficient of q^p in q∏(1−qⁿ)²(1−q¹¹ⁿ)² for p ≤ 50, p ≠ 11', () => {
    const c = eta11Coefficients(60);
    expect(c.slice(1, 11)).toEqual([1, -2, -1, 2, 1, 2, -2, 0, -2, -2]);
    for (const p of primesBelow(51)) {
      if (p === 11) continue;
      const ap = p + 1 - countGeneralWeierstrass(CURVE_11A, p);
      expect(ap, `p=${p}`).toBe(c[p]);
    }
    expect(c[11]).toBe(1);
  });
});

